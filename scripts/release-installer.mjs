/**
 * Publishes a newly built Windows installer to the website.
 *
 * USAGE
 *   npm run release:installer -- "C:\path\to\Business Manager Setup 2.2.0.exe"
 *
 * Optionally pass the version explicitly:
 *   npm run release:installer -- "C:\path\to\setup.exe" 2.2.0
 *
 * WHAT IT DOES
 *   1. Copies the .exe into public/downloads/ under a versioned file name
 *   2. Works out the size and SHA-256 fingerprint
 *   3. Rewrites lib/download.ts so the website button points at it
 *   4. Removes the previous installer, so only one sits in the project
 *
 * WHY THE FILE NAME MUST CHANGE EVERY RELEASE
 *   public/downloads is served with a one-year immutable cache, so a browser
 *   that has already downloaded one file name will never fetch it again.
 *   Putting the version in the file name is what makes browsers download again.
 */
import { copyFile, readdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { basename, join } from "node:path";

const DOWNLOAD_DIR = join(process.cwd(), "public", "downloads");
const CONFIG_FILE = join(process.cwd(), "lib", "download.ts");

const [, , sourceArg, versionArg] = process.argv;

if (!sourceArg) {
  console.error(
    'Usage: npm run release:installer -- "C:\\path\\to\\setup.exe" [version]'
  );
  process.exit(1);
}

const source = sourceArg.replace(/^"|"$/g, "");

// Check the file first: a wrong path is a more useful error than a version
// complaint about the file name you mistyped.
const sourceStat = await stat(source).catch(() => null);

if (!sourceStat) {
  console.error(`Could not find that file:\n  ${source}`);
  console.error(
    "\nIf the folder or file name has spaces, keep the quotes around the path."
  );
  process.exit(1);
}

if (sourceStat.size < 1024) {
  console.error("That file is far too small to be an installer. Check the path.");
  process.exit(1);
}

const version =
  versionArg || (basename(source).match(/(\d+\.\d+\.\d+)/) || [])[1];

if (!version) {
  console.error(
    `Could not read a version number from "${basename(source)}".\n` +
      "Rename the installer so it contains the version, e.g. " +
      '"Business Manager Setup 2.2.0.exe", or pass it: ' +
      'npm run release:installer -- "<file>" 2.2.0'
  );
  process.exit(1);
}

const assetName = `BusinessManager-Setup-${version}.exe`;
const target = join(DOWNLOAD_DIR, assetName);

// An old installer with the same version would be silently ignored by the
// browser cache, so refuse rather than let that happen unnoticed.
const existing = await stat(target).catch(() => null);
if (existing) {
  console.error(`${assetName} is already published.`);
  console.error(
    "Browsers cache that file name for a year, so replacing it would not\n" +
      "reach people who already downloaded it. Bump the version in your app\n" +
      "(package.json), rebuild, then run this again with the new file."
  );
  process.exit(1);
}

await copyFile(source, target);

const { size } = await stat(target);
const sha256 = createHash("sha256")
  .update(await readFile(target))
  .digest("hex")
  .toUpperCase();
const sizeMb = `${(size / 1024 / 1024).toFixed(1)} MB`;

// Keep the human-written requirements line from the existing config.
let requirements = "Windows 10 or 11, 64-bit";
try {
  const existingConfig = await readFile(CONFIG_FILE, "utf8");
  const found = existingConfig.match(/requirements:\s*"([^"]+)"/);
  if (found) requirements = found[1];
} catch {
  /* first run */
}

const config = `/**
 * ABOUT THIS FILE
 *   Generated by: npm run release:installer
 *
 *   Do not hand-edit the values below. Run the release command instead and they
 *   are filled in for you, together with the file name and checksum.
 *
 * TO PUBLISH A NEW VERSION
 *   1. In your app folder, bump the version in package.json and build:
 *        npm run build:win
 *   2. On the website, run:
 *        npm run release:installer -- "..\\\\100-200% completed\\\\dist\\\\<installer>.exe"
 *   3. Build and deploy the website:
 *        npm run build
 *
 * WHERE THE INSTALLER LIVES
 *   In public/downloads, inside this project, so it is deployed together with
 *   the site. Only the newest version is kept.
 *
 * WHY THE FILE NAME CHANGES EACH TIME
 *   That folder is served with a one-year immutable cache, so a browser that
 *   downloaded one file name will never fetch it again. Bumping the version in
 *   the name is what tells customers' browsers to download the new file.
 */
export const download = {
  /** Version shown to customers. */
  version: "${version}",

  /** File name inside public/downloads/. Must not contain spaces. */
  fileName: "${assetName}",

  /** Public path the button links to. */
  url: "/downloads/${assetName}",

  /** Human-friendly size shown on the button. */
  sizeMb: "${sizeMb}",

  /** Real byte size of the file, for checking a download. */
  fileSizeBytes: ${size},

  /** SHA-256 fingerprint, shown so customers can confirm the file is complete. */
  sha256: "${sha256}",

  /** Plain-language system requirements shown next to the button. */
  requirements: "${requirements}"
} as const;
`;

await writeFile(CONFIG_FILE, config, "utf8");

// Keep only the newly published installer in the project.
const installed = (await readdir(DOWNLOAD_DIR)).filter((f) =>
  f.toLowerCase().endsWith(".exe")
);

for (const file of installed) {
  if (file !== assetName) {
    await rm(join(DOWNLOAD_DIR, file));
    console.log(`Removed previous installer: ${file}`);
  }
}

console.log(`Published: ${assetName}  (${sizeMb})`);
console.log(`Updated  : lib/download.ts`);
console.log(`
Done. Version ${version} is ready.

Next: npm run build, then deploy the website.
`);
